"""
Precision-preserving `W₋₁(-exp(lnmz))` for non-Float64 floating types.

The iteration solves `w + log(-w) = lnmz` directly, so very negative `lnmz`
never underflows through construction of `-exp(lnmz)`.
"""
function fast_lambertwm1_from_ln(lnmz::FT) where {FT <: AbstractFloat}
    isnan(lnmz) && return lnmz
    lnmz > -one(FT) && return FT(NaN)
    lnmz == -one(FT) && return -one(FT)
    lnmz == -FT(Inf) && return -FT(Inf)
    distance = -one(FT) - lnmz
    w = if distance < FT(0.25)
        -one(FT) - sqrt(FT(2) * distance) - FT(2) * distance / FT(3)
    else
        lnmz - log(-lnmz)
    end
    tolerance = FT(8) * eps(FT)
    for _ in 1:50
        residual = w + log(-w) - lnmz
        first = one(FT) + inv(w)
        second = -inv(w^2)
        denominator = FT(2) * first^2 - residual * second
        step = FT(2) * residual * first / denominator
        w_new = w - step
        abs(step) ≤ tolerance * max(abs(w_new), one(FT)) && return w_new
        w = w_new
    end
    return w
end
