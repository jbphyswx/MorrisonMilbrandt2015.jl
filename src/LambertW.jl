"""Precision-preserving Halley evaluation of the real principal branch."""
function fast_lambertw0(z::FT) where {FT <: AbstractFloat}
    branch = -inv(exp(one(FT)))
    isnan(z) && return z
    z < branch && return FT(NaN)
    z == branch && return -one(FT)
    iszero(z) && return z
    isinf(z) && return z
    w = if z < zero(FT)
        -one(FT) + sqrt(max(zero(FT), FT(2) * (one(FT) + exp(one(FT)) * z)))
    elseif z < one(FT)
        z
    else
        lz = log(z)
        z > exp(one(FT)) ? lz - log(lz) : log1p(z)
    end
    tolerance = FT(8) * eps(FT)
    for _ in 1:50
        ew = exp(w)
        f = w * ew - z
        denominator = ew * (w + one(FT)) - (w + FT(2)) * f / (FT(2) * (w + one(FT)))
        step = f / denominator
        w_new = w - step
        abs(step) ≤ tolerance * max(abs(w_new), one(FT)) && return w_new
        w = w_new
    end
    return w
end



